/**
 * Writes a static snapshot of the real, Zod-schema-driven OpenAPI
 * document (src/server/openapi/*, same builder that backs the live
 * /api/v1/openapi.json route) to packages/sdk/openapi/schema.json.
 * packages/sdk's own build step runs `openapi-typescript` against that
 * committed snapshot to generate accurate, always-in-sync TS types —
 * this is the single source of truth, not a hand-duplicated set of SDK
 * interfaces that could silently drift from the real API.
 *
 * Run with: npx tsx scripts/generate-sdk-openapi-schema.mjs
 */
import { writeFile, mkdir } from "node:fs/promises";
import path from "node:path";
import { buildOpenApiDocument } from "../src/app/api/v1/openapi.json/route.ts";
import { STATUS_BY_CODE } from "../src/server/http/errors.ts";

const outDir = path.join(process.cwd(), "packages", "sdk", "openapi");
const outFile = path.join(outDir, "schema.json");

const document = buildOpenApiDocument();
await mkdir(outDir, { recursive: true });
await writeFile(outFile, JSON.stringify(document, null, 2) + "\n", "utf8");

console.log(`Wrote OpenAPI schema snapshot -> ${path.relative(process.cwd(), outFile)}`);
console.log(`  ${Object.keys(document.paths).length} paths, ${document.tags.length} tags`);

const errorCodesDir = path.join(process.cwd(), "packages", "sdk", "src", "generated");
const errorCodesFile = path.join(errorCodesDir, "error-codes.ts");
const codes = Object.keys(STATUS_BY_CODE).sort();
const errorCodesSource = `/**
 * This file was auto-generated by scripts/generate-sdk-openapi-schema.mjs
 * from the real STATUS_BY_CODE map in src/server/http/errors.ts.
 * Do not make direct changes to the file.
 */

export type ApiErrorCode =
${codes.map((code) => `  | "${code}"`).join("\n")};

export const STATUS_BY_CODE: Record<ApiErrorCode, number> = ${JSON.stringify(STATUS_BY_CODE, null, 2)};
`;
await mkdir(errorCodesDir, { recursive: true });
await writeFile(errorCodesFile, errorCodesSource, "utf8");
console.log(`Wrote error codes -> ${path.relative(process.cwd(), errorCodesFile)}`);
console.log(`  ${codes.length} real error codes`);
